function lockKgLayout() {
  if (kgLayoutLocked) {
    return;
  }

  if (
    !document.body ||
    !document.body.classList.contains("homepage")
  ) {
    kgLayoutLocked = true;
    return;
  }

  const elements = [];

  kgLayoutSelectors.forEach((selector) => {
    document
      .querySelectorAll(selector)
      .forEach((element) => {
        if (!elements.includes(element)) {
          elements.push(element);
        }
      });
  });

  elements.forEach((element) => {
    const rect = element.getBoundingClientRect();

    if (
      !rect.width ||
      !rect.height
    ) {
      return;
    }

    const computed =
      window.getComputedStyle(element);

    /*
     * Запоминаем именно фактический размер KG,
     * который браузер уже рассчитан.
     */

    element.style.width =
      `${Math.ceil(rect.width)}px`;

    element.style.minWidth =
      `${Math.ceil(rect.width)}px`;

    element.style.maxWidth =
      `${Math.ceil(rect.width)}px`;

    element.style.height =
      `${Math.ceil(rect.height)}px`;

    element.style.minHeight =
      `${Math.ceil(rect.height)}px`;

    element.style.maxHeight =
      `${Math.ceil(rect.height)}px`;

    /*
     * Для flex/grid запрещаем элементу
     * заново менять геометрию.
     */

    if (
      computed.display === "flex" ||
      computed.display === "inline-flex"
    ) {
      element.style.flexShrink = "0";
    }

    /*
     * Длинный перевод не имеет права
     * растягивать коробку.
     */

    element.style.boxSizing =
      "border-box";

    if (
      element.matches(
        "button, .button, .hero-access-card"
      )
    ) {
      element.style.overflow = "hidden";
    }
  });

  /*
   * Особенно важно для шапки:
   * KG / РУС / ENG всегда занимают
   * одинаковые места.
   */

  document
    .querySelectorAll(
      ".lang-switch"
    )
    .forEach((switcher) => {
      const buttons =
        switcher.querySelectorAll(
          "button"
        );

      buttons.forEach((button) => {
        button.style.flexShrink = "0";
        button.style.whiteSpace = "nowrap";
        button.style.overflow = "hidden";
      });
    });

  kgLayoutLocked = true;
}

/* =========================================================
   STANDARD TRANSLATION
   ========================================================= */

export function t(key) {
  return (
    messages[current]?.[key] ??
    messages.ru?.[key] ??
    key
  );
}


/* =========================================================
   DYNAMIC TRANSLATION
   Для значений из БД / Supabase.
   ========================================================= */

export function td(value) {
  if (
    value === null ||
    value === undefined
  ) {
    return "";
  }

  const raw =
    String(value).trim();

  if (!raw) {
    return "";
  }

  return (
    dynamicTranslations[current]?.[raw] ??
    dynamicTranslations.ru?.[raw] ??
    raw
  );
}


