/* =========================================================
   APPLY LANGUAGE
   ========================================================= */

export function applyLanguage(
  lang = current
) {
  current =
    aliases[lang] || "ru";

  try {
    localStorage.setItem(
      "agromal_language",
      current
    );
  } catch {
    // Preference persistence is optional.
  }


  document.documentElement.lang =
    current === "ky"
      ? "ky"
      : current;


  /* =====================================================
     TEXT CONTENT
     ===================================================== */

  document
    .querySelectorAll(
      "[data-i18n]"
    )
    .forEach((element) => {
      const key =
        element.dataset.i18n;

      if (!key) {
        return;
      }

      const value =
        t(key);

      if (
        typeof value === "string" &&
        value.includes("\n")
      ) {
        element.innerHTML =
          value
            .split("\n")
            .map(
              (line) =>
                escapeHtml(line)
            )
            .join("<br>");
      } else {
        element.textContent =
          value;
      }
    });


  /* =====================================================
     PLACEHOLDERS
     ===================================================== */

  document
    .querySelectorAll(
      "[data-i18n-placeholder]"
    )
    .forEach((element) => {
      const key =
        element.dataset
          .i18nPlaceholder;

      if (!key) {
        return;
      }

      element.placeholder =
        t(key);
    });


  /* =====================================================
     ARIA LABELS
     ===================================================== */

  document
    .querySelectorAll(
      "[data-i18n-aria-label]"
    )
    .forEach((element) => {
      const key =
        element.dataset
          .i18nAriaLabel;

      if (!key) {
        return;
      }

      element.setAttribute(
        "aria-label",
        t(key)
      );
    });


  /* =====================================================
     TITLE ATTRIBUTES
     ===================================================== */

  document
    .querySelectorAll(
      "[data-i18n-title]"
    )
    .forEach((element) => {
      const key =
        element.dataset
          .i18nTitle;

      if (!key) {
        return;
      }

      element.setAttribute(
        "title",
        t(key)
      );
    });


  /* =====================================================
     DOCUMENT TITLE
     ===================================================== */

  const titleKey =
    document.documentElement
      .dataset.i18nTitle;

  if (titleKey) {
    document.title =
      t(titleKey);
  }


  /* =====================================================
     LANGUAGE BUTTONS
     ===================================================== */

  document
    .querySelectorAll(
      "[data-lang]"
    )
    .forEach((button) => {
      const active =
        aliases[
          button.dataset.lang
        ] === current;

      button.classList.toggle(
        "is-active",
        active
      );

      button.setAttribute(
        "aria-current",
        String(active)
      );
      button.setAttribute(
        "aria-pressed",
        String(active)
      );
    });


  /* =====================================================
     EVENT
     ===================================================== */

  document.dispatchEvent(
    new CustomEvent(
      "agromal:language",
      {
        detail: current
      }
    )
  );
}


/* =========================================================
   INIT
   ========================================================= */

export function initI18n() {
  document
    .querySelectorAll(
      "[data-lang]"
    )
    .forEach((button) => {
      button.addEventListener(
        "click",
        () => {
          applyLanguage(
            button.dataset.lang
          );
        }
      );
    });

  applyLanguage(current);
}


/* =========================================================
   SAFE HTML ESCAPE
   ========================================================= */

function escapeHtml(value) {
  return String(value)
    .replaceAll(
      "&",
      "&amp;"
    )
    .replaceAll(
      "<",
      "&lt;"
    )
    .replaceAll(
      ">",
      "&gt;"
    )
    .replaceAll(
      '"',
      "&quot;"
    )
    .replaceAll(
      "'",
      "&#039;"
    );
}